-- Trusted one-time seed import. Every insert is in this same transaction; reruns never overwrite edits.
create or replace function public.bootstrap_cms_seed(
  p_seed_version text,
  p_seed_checksum text,
  p_site_config jsonb,
  p_pages jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, safar_private
as $function$
declare
  v_page jsonb;
  v_page_id text;
  v_document jsonb;
  v_section_id uuid;
  v_count integer := 0;
  v_existing_checksum text;
  v_existing_version text;
begin
  if coalesce(auth.jwt() ->> 'role', '') <> 'service_role' then
    raise exception 'CMS bootstrap is restricted to the service role.'
      using errcode = '42501';
  end if;

  if p_seed_version is null or length(btrim(p_seed_version)) = 0 or length(p_seed_version) > 100 then
    raise exception 'A valid seed version is required.'
      using errcode = '22023';
  end if;
  if p_seed_checksum is null or p_seed_checksum !~ '^[0-9a-f]{64}$' then
    raise exception 'A SHA-256 seed checksum is required.'
      using errcode = '22023';
  end if;
  if p_site_config is null
     or jsonb_typeof(p_site_config) is distinct from 'object'
     or jsonb_typeof(p_site_config -> 'site') is distinct from 'object'
     or jsonb_typeof(p_site_config -> 'theme') is distinct from 'object'
     or jsonb_typeof(p_site_config #> '{theme,light}') is distinct from 'object'
     or pg_column_size(p_site_config) > 1000000 then
    raise exception 'Site configuration must include site and light-theme objects under 1 MB.'
      using errcode = '22023';
  end if;

  if coalesce(safar_private.is_safe_theme_color(p_site_config #>> '{theme,light,primary}'), false) = false
     or coalesce(safar_private.is_safe_theme_color(p_site_config #>> '{theme,light,background}'), false) = false
     or coalesce(safar_private.is_safe_theme_color(p_site_config #>> '{theme,light,foreground}'), false) = false then
    raise exception 'Seed contains unsafe or unsupported top-level theme colors.'
      using errcode = '22023';
  end if;

  if p_pages is null or jsonb_typeof(p_pages) is distinct from 'array'
     or jsonb_array_length(p_pages) < 1 or jsonb_array_length(p_pages) > 100
     or pg_column_size(p_pages) > 10000000 then
    raise exception 'Seed pages must be an array of 1-100 documents under 10 MB.'
      using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('safar-cms-seed-bootstrap', 1));

  select seed_checksum, seed_version
    into v_existing_checksum, v_existing_version
    from public.cms_site_config
   where id = 1
   for update;

  if found then
    if v_existing_checksum = p_seed_checksum and v_existing_version = p_seed_version then
      return jsonb_build_object(
        'status', 'already_initialized',
        'published_pages', (select count(*) from public.cms_published_documents),
        'seed_version', v_existing_version
      );
    end if;

    raise exception 'CMS is already initialized with another seed. Bootstrap never overwrites live edits.'
      using errcode = '55000';
  end if;

  if exists (select 1 from public.cms_sections)
     or exists (select 1 from public.cms_revisions)
     or exists (select 1 from public.cms_published_documents)
     or exists (select 1 from public.cms_site_config_revisions) then
    raise exception 'CMS has data but no seed marker. Inspect and reconcile it before bootstrap.'
      using errcode = '55000';
  end if;

  if exists (
    select 1
      from (
        select item.page_doc ->> 'page' as page_key, count(*) as occurrences
          from jsonb_array_elements(p_pages) as item(page_doc)
         group by item.page_doc ->> 'page'
        having count(*) > 1
      ) duplicates
  ) then
    raise exception 'Seed contains duplicate page identifiers.'
      using errcode = '22023';
  end if;

  for v_page in select value from jsonb_array_elements(p_pages)
  loop
    v_page_id := v_page ->> 'page';
    v_document := v_page -> 'document';

    if v_page_id is null
       or v_page_id <> btrim(v_page_id)
       or length(v_page_id) = 0
       or length(v_page_id) > 200
       or v_document is null
       or jsonb_typeof(v_document) is distinct from 'object'
       or v_document ->> 'page' is distinct from v_page_id
       or v_document ->> 'schemaVersion' is distinct from '1'
       or jsonb_typeof(v_document -> 'blocks') is distinct from 'array'
       or jsonb_array_length(v_document -> 'blocks') > 150
       or pg_column_size(v_document) > 2000000
       or jsonb_typeof(v_document -> 'metadata') is distinct from 'object'
       or coalesce(v_document #>> '{metadata,path}', '') !~ '^/[A-Za-z0-9/_-]*$'
       or left(coalesce(v_document #>> '{metadata,path}', ''), 2) = '//'
       or jsonb_typeof(v_document #> '{metadata,seo}') is distinct from 'object'
       or jsonb_typeof(v_document #> '{metadata,seo,title}') is distinct from 'string'
       or jsonb_typeof(v_document #> '{metadata,seo,description}') is distinct from 'string' then
      raise exception 'Seed includes an invalid page envelope or metadata for page %.', coalesce(v_page_id, '<missing>')
        using errcode = '22023';
    end if;

    if exists (
      select 1
        from jsonb_array_elements(v_document -> 'blocks') as item(block)
       where jsonb_typeof(item.block) is distinct from 'object'
          or jsonb_typeof(item.block -> 'id') is distinct from 'string'
          or length(btrim(coalesce(item.block ->> 'id', ''))) = 0
          or length(item.block ->> 'id') > 128
          or coalesce(item.block ->> 'type', '') not in (
            'hero', 'cinematicHero', 'careJourney', 'serviceStory', 'trustDossier',
            'proofReturn', 'serviceFilm', 'storyCarousel', 'invoiceExample', 'heading',
            'text', 'image', 'buttons', 'imageText', 'cards', 'faq', 'contactStrip',
            'enquiryForm', 'video', 'spacer', 'divider', 'navigation'
          )
          or jsonb_typeof(item.block -> 'props') is distinct from 'object'
          or jsonb_typeof(item.block -> 'layout') is distinct from 'object'
          or coalesce(item.block #>> '{layout,align}', '') not in ('left', 'center', 'right')
          or coalesce(item.block #>> '{layout,width}', '') not in ('narrow', 'normal', 'full')
          or coalesce(item.block #>> '{layout,background}', '') not in ('none', 'muted', 'card', 'primary', 'accent')
          or jsonb_typeof(item.block #> '{layout,spaceTop}') is distinct from 'number'
          or jsonb_typeof(item.block #> '{layout,spaceBottom}') is distinct from 'number'
          or (case when jsonb_typeof(item.block #> '{layout,spaceTop}') = 'number'
                   then (item.block #>> '{layout,spaceTop}')::numeric else -1 end) < 0
          or (case when jsonb_typeof(item.block #> '{layout,spaceTop}') = 'number'
                   then (item.block #>> '{layout,spaceTop}')::numeric else 7 end) > 6
          or (case when jsonb_typeof(item.block #> '{layout,spaceBottom}') = 'number'
                   then (item.block #>> '{layout,spaceBottom}')::numeric else -1 end) < 0
          or (case when jsonb_typeof(item.block #> '{layout,spaceBottom}') = 'number'
                   then (item.block #>> '{layout,spaceBottom}')::numeric else 7 end) > 6
          or jsonb_typeof(item.block #> '{layout,hideMobile}') is distinct from 'boolean'
          or jsonb_typeof(item.block #> '{layout,hideDesktop}') is distinct from 'boolean'
    ) then
      raise exception 'Seed page % includes a malformed or unsupported block.', v_page_id
        using errcode = '22023';
    end if;

    if (
      select count(*) <> count(distinct item.block ->> 'id')
        from jsonb_array_elements(v_document -> 'blocks') as item(block)
    ) then
      raise exception 'Seed page % contains duplicate block IDs.', v_page_id
        using errcode = '22023';
    end if;
  end loop;

  insert into public.cms_site_config
    (id, content, seed_version, seed_checksum, version, bootstrapped_at, updated_at)
  values
    (1, p_site_config, p_seed_version, p_seed_checksum, 1, now(), now());

  insert into public.cms_public_site_config (id, content, version, updated_at)
  values (
    1,
    jsonb_build_object(
      'schemaVersion', p_site_config -> 'schemaVersion',
      'site', p_site_config -> 'site',
      'theme', p_site_config -> 'theme'
    ),
    1,
    now()
  );

  insert into public.cms_site_config_revisions (config_version, content, saved_by, saved_at)
  values (1, p_site_config, null, now());

  for v_page in select value from jsonb_array_elements(p_pages)
  loop
    v_page_id := v_page ->> 'page';
    v_document := v_page -> 'document';

    insert into public.cms_sections
      (page, section_key, content, draft_content, status, version, updated_at)
    values
      (v_page_id, '__document', v_document, v_document, 'published', 1, now())
    returning id into v_section_id;

    insert into public.cms_published_documents (page, content, version, updated_at)
    values (v_page_id, v_document, 1, now());

    insert into public.cms_revisions (section_id, content, version, saved_at)
    values (v_section_id, v_document, 1, now());

    v_count := v_count + 1;
  end loop;

  return jsonb_build_object(
    'status', 'initialized',
    'published_pages', v_count,
    'seed_version', p_seed_version
  );
end;
$function$;

